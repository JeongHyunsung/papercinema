"""Writes docs/TIMING_SHEET_V4.md from edl.py and the aligned narration."""
import edl, json
def tc(t):
    m, s = divmod(t, 60); return f"{int(m)}:{s:05.2f}"
L = ["# B-Flex V5 — Timing sheet (generated by `src/timing_sheet.py`)", "",
     f"Runtime **{edl.DURATION:.2f} s** · 3840×2160 · 60 fps · narration-first edit.", "",
     "## 1. Narration placement (word-anchored)", "",
     "Each clip plays at its natural speed. *Anchor* = the word that is locked to an animation event (v3 clock time of that event).", "",
     "| clip | in | out | dur | anchor word → v3 event | text |", "|---|---|---|---|---|---|"]
for c in edl.clips():
    a = edl.ANCHORS[c["id"]]
    if a[1] is None:
        an = f"placed at {a[2]:.2f} s"
    else:
        an = f"“{c['words'][a[0]]['w']}” @ {tc(c['words'][a[0]]['t0'])} → t3 = {a[1]:.2f}"
    L.append(f"| {c['id']} | {tc(c['start'])} | {tc(c['end'])} | {c['end']-c['start']:.2f} | {an} | {c['text']} |")
L += ["", "## 2. Picture edit: v4 clock → animation clock", "",
      "Slope = animation seconds per film second (1 = designed speed; < 0.4 = hold). The race is always at slope 1, so bar durations stay proportional to the measured picoseconds (20 ps per film second).", "",
      "| v4 in | v4 out | v3 range | slope | beat |", "|---|---|---|---|---|"]
t4, t3 = 0.0, edl.T3_START
for e3, d4, note in edl.SEGMENTS:
    L.append(f"| {tc(t4)} | {tc(t4+d4)} | {t3:.2f}–{e3:.2f} | {(e3-t3)/d4:.2f} | {note} |")
    t4 += d4; t3 = e3
L += ["", "## 3. Word timings", "", "Word-level times (v4 clock) for every clip are in `out/audio_v4/placement.json`; per-line source alignments in `narration/words.json`."]
open("../docs/TIMING_SHEET_V5.md", "w").write("\n".join(L) + "\n")
print("ok")
